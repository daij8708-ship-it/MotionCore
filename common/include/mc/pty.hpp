#pragma once

#include <string>

#if defined(__unix__) || defined(__APPLE__)

namespace mc {

// ---------------------------------------------------------------------------
// 开一对伪终端（PTY）。
//
// 伪终端是**内核提供的真 tty**（/dev/pts/N）：读写路径、缓冲、阻塞语义与真串口
// 完全一样，只是对面不是一块板子。它让"设备端能不能在一条 tty 上跑完整会话"
// 这件事在没有硬件、也没有 socat 之类外部工具的情况下可以被验证。
//
// 返回值：master 端的 fd（调用方负责关闭；通常直接交给 FdTransport 托管）。
// slavePath：从端的设备路径，交给对端打开（Qt 侧就是 QSerialPort 的 portName）。
// 失败返回 -1，并且不改动 *slavePath。
//
// 为什么这里自己要设 raw：**master 端没有行规，两个方向的字节都归从端的 termios 管**。
// 默认行规里的 ONLCR / ICRNL 会把二进制载荷里的 0x0A、0x0D 改写成别的字节 ——
// 那是"看起来像 CRC 错"的经典假故障，排查方向会被带偏一整天。
// 从端随后被对端打开时，对端自己还会再设一次（QSerialPort 打开串口时会做），
// 所以这里设的不是"唯一一次"，而是覆盖"对端还没连上来"的那段窗口。
//
// 边界：PTY 不是串口的电气层。波特率、校验位在它上面只是被记录、不起作用，
// 因此"115200 能不能跑满 100 Hz 遥测"这类问题在这里**测不出来**。
// ---------------------------------------------------------------------------
int openPtyPair(std::string* slavePath);

}  // namespace mc

#endif  // __unix__ || __APPLE__
